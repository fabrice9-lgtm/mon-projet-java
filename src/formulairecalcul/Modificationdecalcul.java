    private void RechercherActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RechercherActionPerformed
        // TODO add your handling code here:
        // 1. On récupère l'ID tapé par l'utilisateur
    String idRecherche = idTextField.getText().trim(); 

    // Vérification : l'ID ne doit pas être vide
    if (idRecherche.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Veuillez entrer un ID à rechercher !");
        return;
    }

    try {
    // 2. Connexion à la base de données
        String url = "jdbc:mysql://localhost:3306/iaec_2026";
        String user = "root";
        String pass = "";
        Connection con = DriverManager.getConnection(url, user, pass);

    // 3. Préparation de la requête SELECT
    // On cherche tout (*) là où l'id correspond au '?'
        String query = "SELECT * FROM Table1 WHERE id = ?";
        PreparedStatement pst = con.prepareStatement(query);
        pst.setString(1, idRecherche);

    // 4. Exécution de la requête
    // On utilise ResultSet car on attend un résultat (des données en retour)
        java.sql.ResultSet rs = pst.executeQuery();

        if (rs.next()) {
    // SI ON A TROUVÉ : On récupère les colonnes "Nombre1" et "Nombre2"
    // Et on les affiche dans tes cases de texte
            nombre1FormattedTextField.setText(rs.getString("Nombre1"));
            nombre2FormattedTextField.setText(rs.getString("Nombre2"));
            
            JOptionPane.showMessageDialog(this, "Données trouvées !");
        } else {
    // SI RIEN N'EST TROUVÉ
            JOptionPane.showMessageDialog(this, "Aucun enregistrement trouvé pour cet ID.");
    // On vide les cases par précaution
            nombre1FormattedTextField.setText("");
            nombre2FormattedTextField.setText("");
        }

    // 5. Fermeture
        rs.close();
        pst.close();
        con.close();

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Erreur de recherche : " + ex.getMessage());
    }
    }//GEN-LAST:event_RechercherActionPerformed

