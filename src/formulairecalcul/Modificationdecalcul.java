    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        // 1. On récupère l'ID et les nouvelles valeurs
    String id = idTextField.getText().trim();
    String nombre1 = nombre1FormattedTextField.getText().trim();
    String nombre2 = nombre2FormattedTextField.getText().trim();

    // Vérification : rien ne doit être vide
    if (id.isEmpty() || nombre1.isEmpty() || nombre2.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Tous les champs doivent être remplis !");
        return;
    }

    try {
        // 2. Conversion et calcul de la nouvelle somme
        double n1 = Double.parseDouble(nombre1.replace(',', '.'));
        double n2 = Double.parseDouble(nombre2.replace(',', '.'));
        double nouvelleSomme = n1 + n2;

        // 3. Connexion à la base
        Connection con = DriverManager.getConnection("jdbc:mysql://localhost:3306/iaec_2026", "root", "");

        // 4. Requête UPDATE (On met à jour Nombre1, Nombre2 et la Somme)
        String sql = "UPDATE Table1 SET Nombre1 = ?, Nombre2 = ?, Somme = ? WHERE id = ?";
        PreparedStatement pst = con.prepareStatement(sql);
        
        pst.setDouble(1, n1);
        pst.setDouble(2, n2);
        pst.setDouble(3, nouvelleSomme);
        pst.setString(4, id);

        // 5. Exécution
        int resultat = pst.executeUpdate();

        if (resultat > 0) {
            JOptionPane.showMessageDialog(this, "Modification enregistrée avec succès !");
            // On verrouille à nouveau les cases après l'enregistrement
            nombre1FormattedTextField.setEditable(false);
            nombre2FormattedTextField.setEditable(false);
        }

        pst.close();
        con.close();

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "Erreur lors de la modification : " + ex.getMessage());
    }
    }//GEN-LAST:event_jButton2ActionPerformed

